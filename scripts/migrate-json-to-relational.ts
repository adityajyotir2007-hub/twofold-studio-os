import fs from "fs";
import path from "path";
import { deterministicUuid } from "../src/lib/crypto-vault";
import { SEED_DEMO_IDS } from "../src/lib/initial-data";
import { readAgencyDb, writeAgencyDb } from "../src/lib/server-db";

const DATA_DIR = path.join(process.cwd(), "data");
const BACKUPS_DIR = path.join(DATA_DIR, "backups");
const UPLOADS_DIR = path.join(DATA_DIR, "uploads");
const REPORT_JSON_PATH = path.join(DATA_DIR, "migration-report.json");
const REPORT_MD_PATH = path.join(DATA_DIR, "migration-report.md");
const SQL_SEED_PATH = path.join(
  process.cwd(),
  "supabase",
  "migrations",
  "20261120000003_migrated_data.sql"
);

function sqlStr(val?: string | null): string {
  if (val === undefined || val === null) return "NULL";
  return `'${String(val).replace(/'/g, "''")}'`;
}

async function runMigration() {
  console.log("=== Twofold Studio OS — Part 14 Database Migration & Audit ===");
  const db = readAgencyDb();

  // 1. Create timestamped backup
  if (!fs.existsSync(BACKUPS_DIR)) {
    fs.mkdirSync(BACKUPS_DIR, { recursive: true });
  }
  const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
  const backupFile = path.join(
    BACKUPS_DIR,
    `agency-db-backup-${timestamp}.json`
  );
  fs.writeFileSync(backupFile, JSON.stringify(db, null, 2), "utf-8");
  console.log(`1. Created database backup: ${backupFile}`);

  // 2. Deterministic Workspace UUID
  const workspaceUuid = deterministicUuid("workspace", "twofold-studio");

  // 3. Map legacy IDs to UUID primary keys and classify real vs demo records
  const memberUuidMap = new Map<string, string>();
  const leadUuidMap = new Map<string, string>();
  const clientUuidMap = new Map<string, string>();
  const projectUuidMap = new Map<string, string>();

  for (const m of db.teamMembers) {
    memberUuidMap.set(m.id, deterministicUuid("team_member", m.id));
  }
  for (const l of db.leads) {
    leadUuidMap.set(l.id, deterministicUuid("lead", l.id));
  }
  for (const c of db.clients) {
    clientUuidMap.set(c.id, deterministicUuid("client", c.id));
  }
  for (const p of db.projects) {
    projectUuidMap.set(p.id, deterministicUuid("project", p.id));
  }

  // 4. Validate foreign-key relationships
  const fkWarnings: string[] = [];
  let validFkCount = 0;

  for (const l of db.leads) {
    if (l.assignedTeamMemberId) {
      if (memberUuidMap.has(l.assignedTeamMemberId)) validFkCount++;
      else
        fkWarnings.push(
          `Lead ${l.id} references unknown assignedTeamMemberId ${l.assignedTeamMemberId}`
        );
    }
    if (l.convertedClientId) {
      if (clientUuidMap.has(l.convertedClientId)) validFkCount++;
      else
        fkWarnings.push(
          `Lead ${l.id} references unknown convertedClientId ${l.convertedClientId}`
        );
    }
  }

  for (const p of db.projects) {
    if (clientUuidMap.has(p.clientId)) validFkCount++;
    else fkWarnings.push(`Project ${p.id} references unknown client ${p.clientId}`);
  }

  for (const t of db.tasks) {
    if (t.relatedProjectId && projectUuidMap.has(t.relatedProjectId))
      validFkCount++;
    if (t.assignedPersonId && memberUuidMap.has(t.assignedPersonId))
      validFkCount++;
  }

  for (const f of db.finance) {
    if (f.clientId && clientUuidMap.has(f.clientId)) validFkCount++;
    if (f.projectId && projectUuidMap.has(f.projectId)) validFkCount++;
  }

  // 5. Verify preserved physical document files on disk
  const preservedFiles: {
    docId: string;
    storagePath: string;
    existsOnDisk: boolean;
    bytes: number;
  }[] = [];

  for (const doc of db.documents) {
    const fullPath = path.join(UPLOADS_DIR, doc.storagePath);
    const exists = fs.existsSync(fullPath);
    const bytes = exists ? fs.statSync(fullPath).size : 0;
    preservedFiles.push({
      docId: doc.id,
      storagePath: doc.storagePath,
      existsOnDisk: exists,
      bytes,
    });
  }

  // 6. Generate SQL seed migration file for Supabase PostgreSQL
  const sqlLines: string[] = [
    "-- =============================================================================",
    "-- Twofold Studio OS — 0003 Migrated Relational Data (Generated by Part 14 Script)",
    "-- Seeded demo records are marked with is_demo = true.",
    "-- =============================================================================",
    "",
    `insert into public.workspaces (id, name, slug, settings) values (`,
    `  '${workspaceUuid}', ${sqlStr(db.settings.agencyName)}, 'twofold-studio', ${sqlStr(
      JSON.stringify(db.settings)
    )}::jsonb`,
    `) on conflict (id) do update set settings = excluded.settings;`,
    "",
  ];

  for (const m of db.teamMembers) {
    const uid = memberUuidMap.get(m.id)!;
    const roleCode =
      m.role === "Admin"
        ? "admin"
        : m.role === "Manager"
        ? "manager"
        : "member";
    sqlLines.push(
      `insert into public.team_members (id, workspace_id, name, email, role, title, phone, department, hourly_rate, avatar_initials, status, is_demo, legacy_id) values (` +
        `'${uid}', '${workspaceUuid}', ${sqlStr(m.name)}, ${sqlStr(
          m.email
        )}, '${roleCode}', ${sqlStr(m.title)}, ${sqlStr(m.phone)}, ${sqlStr(
          m.department
        )}, ${m.hourlyRate || 100}, ${sqlStr(
          m.avatarInitials
        )}, 'active', false, ${sqlStr(m.id)}) on conflict (id) do nothing;`
    );
  }

  for (const l of db.leads) {
    const uid = leadUuidMap.get(l.id)!;
    const assignedUid = l.assignedTeamMemberId
      ? memberUuidMap.get(l.assignedTeamMemberId) || null
      : null;
    const isDemo =
      typeof l.isDemo === "boolean" ? l.isDemo : SEED_DEMO_IDS.leads.has(l.id);
    sqlLines.push(
      `insert into public.leads (id, workspace_id, business_name, contact_person, industry, country, city, business_email, phone_number, website_url, instagram_url, facebook_url, linkedin_url, google_maps_url, lead_source, business_description, website_status, rating, number_of_reviews, personalization_notes, potential_opportunity, estimated_project_value, lead_priority, status, assigned_member_id, date_added, last_contacted, next_follow_up_date, is_demo, legacy_id) values (` +
        `'${uid}', '${workspaceUuid}', ${sqlStr(l.businessName)}, ${sqlStr(
          l.contactPerson
        )}, ${sqlStr(l.industry)}, ${sqlStr(l.country)}, ${sqlStr(
          l.city
        )}, ${sqlStr(l.businessEmail)}, ${sqlStr(l.phoneNumber)}, ${sqlStr(
          l.websiteUrl
        )}, ${sqlStr(l.instagramUrl)}, ${sqlStr(l.facebookUrl)}, ${sqlStr(
          l.linkedinUrl
        )}, ${sqlStr(l.googleMapsUrl)}, ${sqlStr(l.leadSource)}, ${sqlStr(
          l.businessDescription
        )}, ${sqlStr(l.websiteStatus)}, ${l.rating || 4.5}, ${
          l.numberOfReviews || 0
        }, ${sqlStr(l.personalizationNotes)}, ${sqlStr(
          l.potentialOpportunity
        )}, ${l.estimatedProjectValue || 0}, ${sqlStr(
          l.leadPriority
        )}, ${sqlStr(l.status)}, ${
          assignedUid ? `'${assignedUid}'` : "NULL"
        }, ${sqlStr(l.dateAdded)}, ${
          l.lastContacted ? sqlStr(l.lastContacted) : "NULL"
        }, ${
          l.nextFollowUpDate ? sqlStr(l.nextFollowUpDate) : "NULL"
        }, ${isDemo}, ${sqlStr(l.id)}) on conflict (id) do nothing;`
    );
  }

  for (const c of db.clients) {
    const uid = clientUuidMap.get(c.id)!;
    const mgrUid = c.assignedAccountManagerId
      ? memberUuidMap.get(c.assignedAccountManagerId) || null
      : null;
    const originLeadUid = c.originLeadId
      ? leadUuidMap.get(c.originLeadId) || null
      : null;
    const isDemo =
      typeof c.isDemo === "boolean"
        ? c.isDemo
        : SEED_DEMO_IDS.clients.has(c.id);
    sqlLines.push(
      `insert into public.clients (id, workspace_id, client_name, business_name, industry, contact_person, email, phone, country, city, website, social_media_links, client_since, total_project_value, payment_status, account_manager_id, internal_notes, origin_lead_id, is_demo, legacy_id) values (` +
        `'${uid}', '${workspaceUuid}', ${sqlStr(c.clientName)}, ${sqlStr(
          c.businessName
        )}, ${sqlStr(c.industry)}, ${sqlStr(c.contactPerson)}, ${sqlStr(
          c.email
        )}, ${sqlStr(c.phone)}, ${sqlStr(c.country)}, ${sqlStr(
          c.city
        )}, ${sqlStr(c.website)}, ${sqlStr(
          JSON.stringify(c.socialMediaLinks || {})
        )}::jsonb, ${sqlStr(c.clientSince)}, ${
          c.totalProjectValue || 0
        }, ${sqlStr(c.paymentStatus)}, ${
          mgrUid ? `'${mgrUid}'` : "NULL"
        }, ${sqlStr(c.internalNotes)}, ${
          originLeadUid ? `'${originLeadUid}'` : "NULL"
        }, ${isDemo}, ${sqlStr(c.id)}) on conflict (id) do nothing;`
    );
  }

  fs.writeFileSync(SQL_SEED_PATH, sqlLines.join("\n"), "utf-8");

  // Save upgraded state with explicit isDemo flags and UUID legacy mappings
  writeAgencyDb(db);

  // 7. Build Migration Report
  const countRealVsDemo = <T extends { isDemo?: boolean }>(items: T[]) => ({
    total: items.length,
    realRecords: items.filter((i) => !i.isDemo).length,
    demoRecords: items.filter((i) => Boolean(i.isDemo)).length,
  });

  const report = {
    migratedAt: new Date().toISOString(),
    workspaceUuid,
    backupFile,
    sqlMigrationSeedFile: SQL_SEED_PATH,
    tables: {
      teamMembers: countRealVsDemo(db.teamMembers),
      leads: countRealVsDemo(db.leads),
      outreach: countRealVsDemo(db.outreach),
      coldCalls: countRealVsDemo(db.coldCalls || []),
      campaigns: countRealVsDemo(db.campaigns || []),
      clients: countRealVsDemo(db.clients),
      projects: countRealVsDemo(db.projects),
      tasks: countRealVsDemo(db.tasks),
      finance: countRealVsDemo(db.finance),
      documents: countRealVsDemo(db.documents),
      templates: countRealVsDemo(db.templates),
    },
    foreignKeyValidation: {
      validatedRelationships: validFkCount,
      warnings: fkWarnings,
      status: fkWarnings.length === 0 ? "ALL_VALID" : "WARNINGS_PRESENT",
    },
    preservedDocuments: preservedFiles,
  };

  fs.writeFileSync(REPORT_JSON_PATH, JSON.stringify(report, null, 2), "utf-8");

  const md = `# Twofold Studio OS — Database Migration Report

- **Timestamp:** ${report.migratedAt}
- **Workspace UUID:** \`${report.workspaceUuid}\`
- **Backup File:** \`${report.backupFile}\`
- **Generated SQL Seed Migration:** \`${report.sqlMigrationSeedFile}\`
- **Foreign-Key Validation Status:** **${report.foreignKeyValidation.status}** (${report.foreignKeyValidation.validatedRelationships} relationships verified, ${report.foreignKeyValidation.warnings.length} broken references)

## Record Classification (Legitimate vs. Seeded Demo Data)

| Table | Total Records | Legitimate Records (\`is_demo = false\`) | Seeded Demo Records (\`is_demo = true\`) |
| :--- | :---: | :---: | :---: |
| \`team_members\` | ${report.tables.teamMembers.total} | ${report.tables.teamMembers.realRecords} | ${report.tables.teamMembers.demoRecords} |
| \`leads\` | ${report.tables.leads.total} | ${report.tables.leads.realRecords} | ${report.tables.leads.demoRecords} |
| \`outreach_activities\` | ${report.tables.outreach.total} | ${report.tables.outreach.realRecords} | ${report.tables.outreach.demoRecords} |
| \`cold_calls\` | ${report.tables.coldCalls.total} | ${report.tables.coldCalls.realRecords} | ${report.tables.coldCalls.demoRecords} |
| \`campaigns\` | ${report.tables.campaigns.total} | ${report.tables.campaigns.realRecords} | ${report.tables.campaigns.demoRecords} |
| \`clients\` | ${report.tables.clients.total} | ${report.tables.clients.realRecords} | ${report.tables.clients.demoRecords} |
| \`projects\` | ${report.tables.projects.total} | ${report.tables.projects.realRecords} | ${report.tables.projects.demoRecords} |
| \`tasks\` | ${report.tables.tasks.total} | ${report.tables.tasks.realRecords} | ${report.tables.tasks.demoRecords} |
| \`finance_records\` | ${report.tables.finance.total} | ${report.tables.finance.realRecords} | ${report.tables.finance.demoRecords} |
| \`documents\` | ${report.tables.documents.total} | ${report.tables.documents.realRecords} | ${report.tables.documents.demoRecords} |
| \`templates\` | ${report.tables.templates.total} | ${report.tables.templates.realRecords} | ${report.tables.templates.demoRecords} |

## Preserved Document Files

${preservedFiles
  .map(
    (f) =>
      `- \`${f.docId}\` → \`${f.storagePath}\` (${
        f.existsOnDisk ? `Verified on disk: ${f.bytes} bytes` : "Missing"
      })`
  )
  .join("\n")}
`;

  fs.writeFileSync(REPORT_MD_PATH, md, "utf-8");
  console.log(`2. Generated SQL migration seed: ${SQL_SEED_PATH}`);
  console.log(`3. Generated migration report: ${REPORT_MD_PATH}`);
  console.log(
    `4. Verified ${validFkCount} foreign-key relationships with ${fkWarnings.length} warnings.`
  );
}

runMigration().catch((err) => {
  console.error(err);
  process.exit(1);
});
